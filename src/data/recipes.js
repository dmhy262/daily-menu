export const generateWeekMenu = (recipes, blacklistedIds, config = {}) => {
  const { adults = 2, children = 0 } = config;
  
  const filteredRecipes = recipes.filter(r => !blacklistedIds.includes(r.id));
  
  const getRecipesByType = (type) => {
    return filteredRecipes.filter(r => r.type === type);
  };
  
  const meatRecipes = getRecipesByType('荤菜');
  const smallMeatRecipes = getRecipesByType('小荤');
  const vegetableRecipes = getRecipesByType('蔬菜');
  const soupRecipes = getRecipesByType('汤');
  
  // 为每个类型维护单独的使用列表
  const usedRecipeIdsByType = {
    '荤菜': [],
    '小荤': [],
    '蔬菜': [],
    '汤': []
  };
  
  const getRandomRecipe = (recipeList, type) => {
    if (!recipeList || recipeList.length === 0) {
      return null;
    }
    
    const usedRecipeIds = usedRecipeIdsByType[type] || [];
    let available = recipeList.filter(r => r && r.id && !usedRecipeIds.includes(r.id));
    
    // 如果有未使用的，优先从未使用的选
    if (available.length > 0) {
      const shuffled = [...available].sort(() => Math.random() - 0.5);
      const selected = shuffled[0];
      if (selected && selected.id) {
        usedRecipeIdsByType[type].push(selected.id);
      }
      return selected;
    }
    
    // 否则重置使用记录，重新开始
    usedRecipeIdsByType[type] = [];
    const shuffled = [...recipeList].filter(r => r && r.id).sort(() => Math.random() - 0.5);
    if (shuffled.length > 0) {
      const selected = shuffled[0];
      usedRecipeIdsByType[type].push(selected.id);
      return selected;
    }
    return null;
  };
  
  const weekDays = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
  const weekNames = ['周一', '周二', '周三', '周四', '周五', '周六', '周日'];
  
  const result = [];
  
  weekDays.forEach((day, index) => {
    const dayMenu = {
      id: day,
      name: weekNames[index],
      lunch: [],
      dinner: []
    };
    
    // 晚餐：荤菜 + 小荤 + 蔬菜 + 汤（每个类型单独保证不重复）
    const dinnerMeat = getRandomRecipe(meatRecipes, '荤菜');
    if (dinnerMeat) {
      dayMenu.dinner.push({ recipe: dinnerMeat, portion: '荤菜' });
    }
    
    const dinnerSmallMeat = getRandomRecipe(smallMeatRecipes, '小荤');
    if (dinnerSmallMeat) {
      dayMenu.dinner.push({ recipe: dinnerSmallMeat, portion: '小荤' });
    }
    
    const dinnerVeg = getRandomRecipe(vegetableRecipes, '蔬菜');
    if (dinnerVeg) {
      dayMenu.dinner.push({ recipe: dinnerVeg, portion: '蔬菜' });
    }
    
    const dinnerSoup = getRandomRecipe(soupRecipes, '汤');
    if (dinnerSoup) {
      dayMenu.dinner.push({ recipe: dinnerSoup, portion: '汤' });
    }
    
    result.push(dayMenu);
  });
  
  return result;
};
